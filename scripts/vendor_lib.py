#!/usr/bin/env python3
"""Bundle the client library into the integration and build release copies.

``lib/src/prusa_connect`` is the only source of the library. The
integration carries a generated copy in ``_vendor/`` so that it works without
the package on PyPI. This script writes that copy, checks it, and builds the
integration folder a release ships.

The release mode is set once, in ``pyproject.toml``::

    [tool.prusa-connect.packaging]
    library = "bundled"   # or "pypi"

- ``bundled``: the release ships the copy; ``manifest.json`` lists only the
  library's dependencies that Home Assistant does not install itself.
- ``pypi``: the release leaves the copy out and ``manifest.json`` requires
  ``prusa-connect==<lib version>``.

The repository itself always holds the bundled shape, so tests, hassfest and
HACS see the same tree in both modes.

Usage::

    scripts/vendor_lib.py sync                 # rewrite the copy and the manifest requirements
    scripts/vendor_lib.py check                # fail when either is out of date
    scripts/vendor_lib.py mode                 # print the release mode
    scripts/vendor_lib.py build --out build    # build/prusa_connect for the release
"""

from __future__ import annotations

import argparse
import filecmp
import json
import re
import shutil
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB_PYPROJECT = ROOT / "lib" / "pyproject.toml"
LIB_SOURCE = ROOT / "lib" / "src" / "prusa_connect"
INTEGRATION = ROOT / "custom_components" / "prusa_connect_ce"
VENDOR = INTEGRATION / "_vendor"
VENDORED = VENDOR / "prusa_connect"
MANIFEST = INTEGRATION / "manifest.json"
MODES = ("bundled", "pypi")
IGNORE = shutil.ignore_patterns("__pycache__", "*.py[cod]")

VENDOR_INIT = '''"""A copy of the prusa-connect client library, bundled with the integration.

Generated by scripts/vendor_lib.py from lib/src/prusa_connect; do not edit.
"""
'''


def packaging() -> tuple[str, list[str]]:
    """The release mode and the dependencies Home Assistant provides."""
    with (ROOT / "pyproject.toml").open("rb") as file:
        section = tomllib.load(file)["tool"]["prusa-connect"]["packaging"]
    mode = section.get("library")
    if mode not in MODES:
        sys.exit(f"tool.prusa-connect.packaging.library must be one of {MODES}, not {mode!r}")
    return str(mode), [str(name) for name in section.get("provided-by-home-assistant", [])]


def library_project() -> tuple[str, str, list[str]]:
    """The library's name, version and dependencies."""
    with LIB_PYPROJECT.open("rb") as file:
        project = tomllib.load(file)["project"]
    return (
        str(project["name"]),
        str(project["version"]),
        [str(dep) for dep in project.get("dependencies", [])],
    )


def requirement_name(requirement: str) -> str:
    match = re.match(r"[A-Za-z0-9._-]+", requirement)
    assert match, requirement
    return re.sub(r"[-_.]+", "-", match.group(0)).lower()


def requirements(mode: str) -> list[str]:
    """The manifest requirements of a release in the given mode."""
    name, version, dependencies = library_project()
    if mode == "pypi":
        return [f"{name}=={version}"]
    provided = {requirement_name(dep) for dep in packaging()[1]}
    return [dep for dep in dependencies if requirement_name(dep) not in provided]


def read_manifest(path: Path = MANIFEST) -> dict[str, object]:
    manifest: dict[str, object] = json.loads(path.read_text())
    return manifest


def write_manifest(manifest: dict[str, object], path: Path = MANIFEST) -> None:
    path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")


def differences(left: Path, right: Path) -> list[str]:
    """Files that differ between two trees, ignoring bytecode caches."""
    if not right.is_dir():
        return [f"{right.relative_to(ROOT)} is missing"]
    found: list[str] = []
    compare = filecmp.dircmp(left, right, ignore=["__pycache__"])

    def walk(cmp: filecmp.dircmp[str], prefix: str) -> None:
        found.extend(f"only in lib: {prefix}{name}" for name in cmp.left_only)
        found.extend(f"only in the copy: {prefix}{name}" for name in cmp.right_only)
        # dircmp compares by stat signature first; compare contents to be sure.
        found.extend(
            f"differs: {prefix}{name}"
            for name in cmp.common_files
            if not filecmp.cmp(Path(cmp.left) / name, Path(cmp.right) / name, shallow=False)
        )
        for name, sub in cmp.subdirs.items():
            walk(sub, f"{prefix}{name}/")

    walk(compare, "")
    return found


def sync() -> None:
    if VENDORED.exists():
        shutil.rmtree(VENDORED)
    VENDOR.mkdir(exist_ok=True)
    shutil.copytree(LIB_SOURCE, VENDORED, ignore=IGNORE)
    (VENDOR / "__init__.py").write_text(VENDOR_INIT)
    manifest = read_manifest()
    manifest["requirements"] = requirements("bundled")
    write_manifest(manifest)
    print(f"bundled {LIB_SOURCE.relative_to(ROOT)} into {VENDORED.relative_to(ROOT)}")


def check() -> int:
    problems = differences(LIB_SOURCE, VENDORED)
    init = VENDOR / "__init__.py"
    if not init.is_file() or init.read_text() != VENDOR_INIT:
        problems.append(f"{init.relative_to(ROOT)} is not the generated file")
    expected = requirements("bundled")
    actual = read_manifest().get("requirements")
    if actual != expected:
        problems.append(f"manifest.json requirements are {actual}, expected {expected} in the bundled shape")
    if problems:
        print("The bundled library is out of date; run scripts/vendor_lib.py sync.", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    print("bundled library matches lib/")
    return 0


def build(out: Path, mode: str) -> None:
    if check():
        sys.exit(1)
    target = out / INTEGRATION.name
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(INTEGRATION, target, ignore=IGNORE)
    if mode == "pypi":
        shutil.rmtree(target / VENDOR.name)
    manifest = read_manifest(target / "manifest.json")
    manifest["requirements"] = requirements(mode)
    write_manifest(manifest, target / "manifest.json")
    print(f"built {target} ({mode}): requirements {manifest['requirements']}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("sync", help="rewrite the bundled copy and the manifest requirements")
    commands.add_parser("check", help="fail when the bundled copy or the manifest is out of date")
    commands.add_parser("mode", help="print the release mode from pyproject.toml")
    build_parser = commands.add_parser("build", help="build the integration folder for a release")
    build_parser.add_argument("--out", type=Path, required=True)
    build_parser.add_argument(
        "--mode", choices=MODES, help="override the mode from pyproject.toml (for testing a build)"
    )
    args = parser.parse_args()
    if args.command == "sync":
        sync()
    elif args.command == "check":
        return check()
    elif args.command == "mode":
        print(packaging()[0])
    else:
        build(args.out, args.mode or packaging()[0])
    return 0


if __name__ == "__main__":
    sys.exit(main())
